#!/usr/bin/env bash
# Full CyberScape cycle with two robots: nothing is placed by hand.
#
#   mission text -> CyberScape LLM planning (Manager.py per robot: high level, low level,
#   verification, parsing) -> HITL review (dashboard or here) -> plan sender -> MAPPO in Isaac Sim
#
#   ./run_cyberscape_mappo_full_cycle.sh                 disaster mission (mission_files/rl_mappo_disaster_mission.txt)
#   ./run_cyberscape_mappo_full_cycle.sh MISSION_TXT     any mission text on the disaster layout
#
# Needs a working cohere_api_key in config.json. Planning two robots takes several minutes.
set -euo pipefail

HERE="$(cd "$(dirname "$0")" && pwd)"
REPO="$(cd "$HERE/../../.." && pwd)"
MISSION="$(realpath "${1:-$REPO/mission_files/rl_mappo_disaster_mission.txt}")"
SERVER="http://localhost:5001"
SERVER_LOG="$HERE/results/mappo_server.log"
DEMO_DIR="$HOME/cyberscape_mappo_demo"

say() { printf '\n\033[1m== %s\033[0m\n' "$*"; }

say "Mission"
fold -s -w 100 "$MISSION"; echo

say "Starting Isaac Sim (MAPPO bridge) and the CyberScape server (1-2 min) ..."
rm -f "$SERVER_LOG"
setsid nohup "$HERE/run_cyberscape_mappo_demo.sh" disaster --live > "$SERVER_LOG" 2>&1 < /dev/null &
until grep -q "Running on" "$SERVER_LOG" 2>/dev/null; do
    if grep -qE "^Traceback|Bridge failed" "$SERVER_LOG" 2>/dev/null; then
        echo "Start-up failed, see $SERVER_LOG"; exit 1
    fi
    sleep 3
done
echo "Ready."

say "CyberScape planning both robots with the LLM (high level -> low level -> verification -> parsing) ..."
python3 - "$MISSION" "$SERVER" <<'EOF'
import json, sys, time, urllib.error, urllib.request
begin = time.perf_counter()
request = urllib.request.Request(sys.argv[2] + "/generate_plan", method="POST",
    data=json.dumps({"mission_title": "rl_mappo_disaster_live", "mission_text": open(sys.argv[1]).read()}).encode(),
    headers={"Content-Type": "application/json"})
try:
    with urllib.request.urlopen(request, timeout=2400) as response:
        print(json.loads(response.read())["message"])
except urllib.error.HTTPError as error:
    sys.exit(f"Planning failed: {error.read().decode()[:400]}")
print(f"Planning took {time.perf_counter() - begin:.0f} s (wall clock).")
EOF

say "Plan generated by CyberScape (phases with the same number run at the same time)"
python3 - "$DEMO_DIR" "$HERE" <<'EOF'
import json, sys
from pathlib import Path
sys.path.insert(0, sys.argv[2])
from cyberscape_mappo_mission import merge_plans
plans = {f"TURTLEBOT3_{k}": json.load(open(Path(sys.argv[1]) / f"Plans/rl_mappo_live_tb3_{k}_plan.json")) for k in (1, 2)}
for name, plan in plans.items():
    print(f"{name}:")
    for phase in plan["phases"]:
        print(f"  Phase {phase['phase_number']}: {phase['phase_target']}")
print()
for number, lines in merge_plans(plans):
    print(f"Phase {number}:")
    for line in lines:
        print(f"    {line}")
EOF
echo
echo "Review it in the dashboard (http://localhost:5001/dashboard/index.html) or here."
read -r -p "Approve this plan and let the robots execute it? [y/N] " answer
if [[ ! "$answer" =~ ^[Yy] ]]; then
    curl -s -X POST -H 'Content-Type: application/json' -d '{"reason":"rejected by operator"}' "$SERVER/hitl/reject_plan" >/dev/null
    echo "Plan rejected. Nothing was executed."
    exit 0
fi
SENDER_LOG="$REPO/cyberscape_sender.log"
sender_start=$(cat "$SENDER_LOG" 2>/dev/null | wc -l)
curl -s -X POST -H 'Content-Type: application/json' -d '{"comments":"approved in terminal"}' "$SERVER/hitl/approve_plan" >/dev/null

say "Approved. MAPPO executing the plan in Isaac Sim:"
BRIDGE_LOG="$HERE/results/mappo_bridge.log"
shown=$(wc -l < "$BRIDGE_LOG")
finished=0
while [ "$finished" -eq 0 ]; do
    tail -n +"$((sender_start + 1))" "$SENDER_LOG" 2>/dev/null | grep -q "MAPPO mission \(complete\|stopped\)" && finished=1
    total=$(wc -l < "$BRIDGE_LOG")
    if [ "$total" -gt "$shown" ]; then
        sed -n "$((shown + 1)),${total}p" "$BRIDGE_LOG" | grep "CYBERSCAPE_MAPPO" || true
        shown=$total
    fi
    sleep 2
done
tail -n +"$((sender_start + 1))" "$SENDER_LOG" | grep "MAPPO mission"
say "Mission finished. Isaac Sim and the server keep running; close the Isaac window to quit."
